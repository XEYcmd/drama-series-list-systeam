def write_bat(name, body):
    bad = sorted({ch for ch in body if ord(ch) > 127})
    if bad:
        print("生成中止：%s 的模板里出现了非 ASCII 字符 %r" % (name, bad))
        return False
    body = body.replace("\r\n", "\n").replace("\n", "\r\n")      # 必须 CRLF
    data = body.encode("ascii")
    with open(os.path.join(ROOT, name), "wb") as fh:
        fh.write(data)
    print("已生成：%s  （ASCII %d 字节 / CRLF %d 行）" % (name, len(data), body.count("\r\n")))
    return True


def main() -> int:
    for spec in TARGETS:
        body = (TEMPLATE
                .replace("%EXTRA_ARGS%", spec["extra_args"])
                .replace("%EXTRA_REM%", spec["extra_rem"]))
        if not write_bat(spec["file"], body):
            return 1
    for spec in EXTRA_FILES:
        if not write_bat(spec["file"], spec["body"]):
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
